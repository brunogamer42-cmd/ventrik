inline bool armar_rsa_de_prueba(mbedtls_rsa_context& rsa, std::size_t cual) {
  mbedtls_mpi p;
  mbedtls_mpi q;
  mbedtls_mpi e;
  mbedtls_mpi_init(&p);
  mbedtls_mpi_init(&q);
  mbedtls_mpi_init(&e);
  const auto liberar = gsl::finally([&] {
    mbedtls_mpi_free(&e);
    mbedtls_mpi_free(&q);
    mbedtls_mpi_free(&p);
  });
  return cual < 2 && mbedtls_mpi_read_string(&p, 16, kPrimosRsaDePrueba[cual][0]) == 0 &&
         mbedtls_mpi_read_string(&q, 16, kPrimosRsaDePrueba[cual][1]) == 0 && mbedtls_mpi_lset(&e, 65537) == 0 &&
         mbedtls_rsa_import(&rsa, nullptr, &p, &q, nullptr, &e) == 0 && mbedtls_rsa_complete(&rsa) == 0 &&
         mbedtls_rsa_check_privkey(&rsa) == 0 && mbedtls_rsa_get_len(&rsa) == 256;
}

